/** Icon names used by `src/config/navigation.ts`, resolved in the renderer. */
const NAV_ICON_COMPONENTS: Record<string, LucideIcon> = {
  Activity,
  BadgePercent,
  BarChart3,
  BookOpen,
  Bot,
  Boxes,
  Building2,
  FileSpreadsheet,
  FileText,
  FlaskConical,
  HelpCircle,
  Landmark,
  LayoutDashboard,
  Package,
  PiggyBank,
  Pill,
  Receipt,
  ShieldAlert,
  ShieldCheck,
  Stethoscope,
  TrendingDown,
  TrendingUp,
  UserCheck,
  Users,
};

export function navIcon(name: string | undefined): LucideIcon {
  return (name ? NAV_ICON_COMPONENTS[name] : undefined) ?? LayoutDashboard;
}
