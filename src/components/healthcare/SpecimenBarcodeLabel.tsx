import { useTranslation } from 'react-i18next';
import { Barcode, Printer } from 'lucide-react';
import { Button } from '@/components/ui/Button';
import { HealthcareModal } from '@/components/healthcare/HealthcareModal';
import { useBrandTheme } from '@/hooks/useBrandTheme';
import { buildCode39Svg } from '@/lib/healthcare/barcode';
import { buildSpecimenLabelHtml, printHtmlDocument } from '@/lib/healthcare/print';

export interface SpecimenLabelPayload {
  patientName: string;
  mrn: string;
  specimenType: string;
  testNames: string[];
  barcode: string;
  collectedAt: string;
}

/** 58mm specimen sticker with a native SVG Code 39 barcode. */
export function SpecimenBarcodeLabel({
  open,
  onClose,
  payload,
}: {
  open: boolean;
  onClose: () => void;
  payload: SpecimenLabelPayload | null;
}) {
  const { t } = useTranslation();
  const { businessName } = useBrandTheme();

  if (!payload) return null;

  const barcodeSvg = buildCode39Svg(payload.barcode, {
    width: 220,
    height: 54,
    showText: false,
  });

  const handlePrint = () => {
    const html = buildSpecimenLabelHtml({
      businessName,
      patientName: payload.patientName,
      mrn: payload.mrn,
      specimenType: payload.specimenType,
      testNames: payload.testNames,
      barcode: payload.barcode,
      collectedAt: payload.collectedAt,
      labels: {
        title: t('healthcare.lab.specimenLabel.title'),
        patient: t('healthcare.lab.specimenLabel.patient'),
        mrn: t('healthcare.lab.specimenLabel.mrn'),
        specimenType: t('healthcare.lab.specimenLabel.specimenType'),
        tests: t('healthcare.lab.specimenLabel.tests'),
        collected: t('healthcare.lab.specimenLabel.collected'),
        barcode: t('healthcare.lab.specimenLabel.barcode'),
      },
    });
    printHtmlDocument(html, 'ledgr-specimen-label-frame');
  };

  return (
    <HealthcareModal
      open={open}
      titleId="specimen-label-title"
      title={t('healthcare.lab.specimenLabel.modalTitle')}
      subtitle={t('healthcare.lab.specimenLabel.modalSubtitle')}
      closeLabel={t('healthcare.common.close')}
      onClose={onClose}
      width="max-w-md"
      footer={
        <>
          <Button variant="secondary" onClick={onClose}>
            {t('healthcare.common.close')}
          </Button>
          <Button onClick={handlePrint}>
            <Printer className="h-4 w-4" aria-hidden />
            {t('healthcare.lab.specimenLabel.print')}
          </Button>
        </>
      }
    >
      <div className="rounded-xl border border-dashed border-gray-300 bg-white p-4">
        <div className="flex items-center gap-2 border-b border-dashed border-gray-300 pb-2">
          <Barcode className="h-4 w-4 text-brand-600" aria-hidden />
          <div>
            <p className="text-[11px] font-bold uppercase tracking-wide text-gray-700">
              {businessName}
            </p>
            <p className="text-[10px] text-gray-500">{t('healthcare.lab.specimenLabel.title')}</p>
          </div>
        </div>

        <div
          className="mt-3 flex justify-center [&>svg]:h-auto [&>svg]:w-full"
          // The SVG is generated by buildCode39Svg from a sanitised code; no
          // user HTML is interpolated.
          dangerouslySetInnerHTML={{ __html: barcodeSvg }}
        />
        <p className="mt-1 text-center font-mono text-xs font-bold tracking-[0.12em] text-gray-900">
          {payload.barcode}
        </p>

        <dl className="mt-3 space-y-1 text-[11px] text-gray-600">
          <div className="flex justify-between gap-2">
            <dt>{t('healthcare.lab.specimenLabel.patient')}</dt>
            <dd className="font-medium text-gray-800">{payload.patientName}</dd>
          </div>
          <div className="flex justify-between gap-2">
            <dt>{t('healthcare.lab.specimenLabel.mrn')}</dt>
            <dd className="font-mono text-gray-800">{payload.mrn}</dd>
          </div>
          <div className="flex justify-between gap-2">
            <dt>{t('healthcare.lab.specimenLabel.specimenType')}</dt>
            <dd className="font-medium text-gray-800">{payload.specimenType}</dd>
          </div>
          <div className="flex justify-between gap-2">
            <dt>{t('healthcare.lab.specimenLabel.collected')}</dt>
            <dd className="font-medium text-gray-800">{payload.collectedAt}</dd>
          </div>
        </dl>

        <div className="mt-2 border-t border-dashed border-gray-300 pt-2">
          <p className="text-[11px] font-semibold text-gray-700">
            {t('healthcare.lab.specimenLabel.tests')}
          </p>
          <ul className="mt-1 list-disc space-y-0.5 pl-4 text-[11px] text-gray-600">
            {payload.testNames.map((name) => (
              <li key={name}>{name}</li>
            ))}
          </ul>
        </div>
      </div>
    </HealthcareModal>
  );
}
