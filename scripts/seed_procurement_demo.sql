-- ============================================================================
-- P3-2 — Demo procurement chain seed (DATA ONLY — this is NOT a migration)
-- ============================================================================
-- Seeds a realistic construction procurement chain into the live demo business
-- so the full flow is demonstrable in the UI:
--
--   Supplier → Site → Purchase Order → Goods Receipt (GRN)
--            → Supplier Bill Match → Material Issue → Material Return
--
-- Target   : business d38e4ce8-324b-4d27-b42d-74c25c5288a7 ("demo@ledgr.test")
-- How to run: paste the whole file into the Supabase SQL endpoint / execute_query
--            for project hsuhuvuxfuufrlejsatw (runs as postgres, single
--            transaction; the final SELECT returns the verification snapshot).
--
-- Idempotency: every step is guarded (NOT EXISTS on natural keys, fixed
-- deterministic client_keys for the RPC commands, status checks before
-- transitions). Re-running the file is a no-op that re-emits the snapshot.
--
-- Design rules honoured:
--   * No schema, trigger, RPC, RLS or capability-machinery changes; no new
--     products, branches, locations or projects. Suppliers only (no
--     construction-client contacts). MWK only. Existing products are used with
--     their real base units (BAG / LENGTH / EACH / M3) — no UoM conversions.
--   * Construction procurement never posts to the general ledger: bills stay
--     draft, receipts/issues/returns move stock only (journal_effect 'none').
--     Debits = credits must be unchanged after the seed.
--   * Stock effects ARE expected (by product design) once the receipt posting
--     policy is approved: accepted+cost-based receipt quantities arrive in
--     inventory at evidenced bill cost, issues/returns move the pool. Frozen
--     counts (projects 5, products 50, BOMs 8, work orders 7, JEs 80) do not
--     change; stock_movements and inventory_balances may grow by the chain's
--     own movements.
--
-- Documented deviations from the seed spec (see PR/report):
--   1. PO status vocabulary is draft/authorized/cancelled; the spec's
--      "completed"/"in_progress" states are represented as: authorized + fully
--      received & matched ("completed"), authorized + not yet received
--      ("in progress"), draft (PO-004).
--   2. po_number/grn_number are server-generated by the RPCs (e.g. PO-000001),
--      not the spec's PO-2026-00N labels; the spec labels are kept as notes /
--      bill references where free text allows.
--   3. Steel Rebar Y12 is stocked per LENGTH (12 m bar ≈ 10.7 kg), so the
--      spec's "2000 kg @ 9,000/kg = 18M" becomes 200 lengths @ 90,000 = 18M
--      (same value; ≈ 2,130 kg). Issues/returns follow LENGTH units.
--   4. authorize_construction_purchase_order enforces two-person authorization
--      (creator ≠ authorizer). The demo has exactly ONE user with procurement
--      grants, and the seed constraints forbid adding grants — so the four POs
--      are authorized through the same internal transition token the RPC uses
--      ('ledgr.construction_command' = 'po_transition', the task's sanctioned
--      Option B), with authorized_by = the demo owner (honest attribution, no
--      fabricated second approver) and an event row that says it was seeded.
--   5. "School Block Renovation" exists twice in construction_projects; the
--      FIRST-created row (79060e02-…) is linked to SITE-SCHOOL deterministically.
--   6. The spec lists BuildRight Supplies as contact_type 'both', but
--      create_construction_purchase_order only accepts contact_type = 'supplier'
--      exactly ('both' is refused), so BuildRight is seeded as 'supplier' — it
--      still cannot be a construction client (that machinery is untouched).
-- ============================================================================

